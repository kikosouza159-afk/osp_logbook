-- ETL Oportunidade Locator: uma linha por servidor, data e campanha.
-- Dados brutos preservados; as médias, taxas e o índice são calculados na interface.
CREATE TABLE IF NOT EXISTS public.osp_locator_opportunity_daily (
  source_host inet NOT NULL,
  data date NOT NULL,
  campaign_id text NOT NULL,
  nome_servidor text NOT NULL,
  cliente text NOT NULL,
  mapping_status text NOT NULL DEFAULT 'UNRESOLVED'
    CHECK (mapping_status IN ('RESOLVED','UNRESOLVED')),
  nome_campanha text NOT NULL,
  virtual_agent_type_id integer,
  mailing bigint CHECK (mailing IS NULL OR mailing >= 0),
  mailing_source_date date,
  logados bigint NOT NULL CHECK (logados >= 0),
  tentativas bigint NOT NULL CHECK (tentativas >= 0),
  atendidas bigint NOT NULL CHECK (atendidas >= 0),
  data_hora_carga timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (source_host, data, campaign_id),
  CONSTRAINT locator_mailing_date_valid CHECK (mailing_source_date IS NULL OR mailing_source_date <= data)
);
CREATE INDEX IF NOT EXISTS osp_locator_opportunity_daily_data_idx
  ON public.osp_locator_opportunity_daily (data DESC, cliente, campaign_id);
CREATE INDEX IF NOT EXISTS osp_locator_opportunity_daily_client_idx
  ON public.osp_locator_opportunity_daily (cliente, data DESC);

CREATE TABLE IF NOT EXISTS public.osp_locator_opportunity_etl_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_host inet NOT NULL,
  load_date date NOT NULL,
  status text NOT NULL CHECK (status IN ('SUCCESS','PARTIAL','EMPTY','SKIPPED','FAILED')),
  row_count integer NOT NULL DEFAULT 0,
  message text,
  loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS osp_locator_opportunity_etl_log_recent_idx
  ON public.osp_locator_opportunity_etl_log (loaded_at DESC);
