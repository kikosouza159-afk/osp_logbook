CREATE TABLE IF NOT EXISTS osp_financial_billing (
  source_host inet NOT NULL,
  cliente text NOT NULL,
  nome_servidor text NOT NULL,
  data date NOT NULL,
  logados bigint NOT NULL CHECK (logados >= 0),
  campaign_id text NOT NULL,
  nome_campanha text NOT NULL,
  virtual_agent_type_id text NOT NULL,
  chamadas_tarifadas bigint NOT NULL CHECK (chamadas_tarifadas >= 0),
  valor_tarifado numeric(28,8) NOT NULL,
  data_hora_carga timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (source_host,data,campaign_id,virtual_agent_type_id)
);
CREATE INDEX IF NOT EXISTS osp_financial_billing_data_idx ON osp_financial_billing(data,cliente);
CREATE TABLE IF NOT EXISTS osp_financial_etl_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_host inet NOT NULL,
  load_date date NOT NULL,
  status text NOT NULL CHECK (status IN ('SUCCESS','EMPTY','FAILED')),
  row_count integer NOT NULL DEFAULT 0,
  message text,
  loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS osp_financial_etl_log_recent_idx ON osp_financial_etl_log(loaded_at DESC);
